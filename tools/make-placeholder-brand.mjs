#!/usr/bin/env node
/**
 * Generates neutral placeholder brand marks into brand/logos/.
 *
 * The real institutional marks are trademarks and are gitignored, so a fresh
 * clone has nothing to render. Rather than fail or draw empty boxes, ship
 * generic stand-ins that exercise every code path the real ones do: a wide
 * banner, a square crest with transparency, and a watermark.
 *
 * Existing files are never overwritten — running this after dropping in real
 * logos is a no-op.
 *
 *   node tools/make-placeholder-brand.mjs
 */
import { mkdir, access, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";
import { ROOT } from "../src/paths.js";

const OUT = path.join(ROOT, "brand", "logos");

const INK = "#2f3b52";
const ACCENT = "#b4472f";

const exists = (p) => access(p).then(() => true, () => false);

/** Wide department strip — the mark used on title slides and report headers. */
const bannerSVG = `
<svg xmlns="http://www.w3.org/2000/svg" width="1600" height="253" viewBox="0 0 1600 253">
  <rect width="1600" height="253" fill="#ffffff"/>
  <rect x="40" y="42" width="150" height="150" rx="10" fill="${ACCENT}"/>
  <text x="115" y="140" font-family="DejaVu Sans, sans-serif" font-size="62" font-weight="bold"
        fill="#ffffff" text-anchor="middle">EX</text>
  <text x="800" y="86" font-family="DejaVu Serif, serif" font-size="40" font-weight="bold"
        fill="${INK}" text-anchor="middle">EXAMPLE INSTITUTE OF TECHNOLOGY</text>
  <text x="800" y="132" font-family="DejaVu Sans, sans-serif" font-size="29"
        fill="${INK}" text-anchor="middle">Department of Computer Engineering</text>
  <text x="800" y="172" font-family="DejaVu Sans, sans-serif" font-size="23"
        fill="#6b7280" text-anchor="middle">Placeholder mark — replace in brand/logos/</text>
  <rect x="1410" y="52" width="150" height="150" rx="10" fill="none" stroke="${INK}" stroke-width="6"/>
  <text x="1485" y="140" font-family="DejaVu Serif, serif" font-size="52" font-weight="bold"
        fill="${INK}" text-anchor="middle">EIT</text>
  <rect x="0" y="245" width="1600" height="8" fill="${INK}"/>
</svg>`;

/** Square crest. Deliberately drawn on white so prep-brand's keying is exercised. */
const crestSVG = `
<svg xmlns="http://www.w3.org/2000/svg" width="447" height="447" viewBox="0 0 447 447">
  <rect width="447" height="447" fill="#ffffff"/>
  <path d="M223 70 L340 108 v120 c0 74-52 118-117 139-65-21-117-65-117-139V108Z"
        fill="${INK}" stroke="${ACCENT}" stroke-width="9"/>
  <path d="M223 108 v229" stroke="#ffffff" stroke-width="5" opacity="0.5"/>
  <path d="M110 200 h226" stroke="#ffffff" stroke-width="5" opacity="0.5"/>
  <circle cx="223" cy="168" r="26" fill="${ACCENT}"/>
  <text x="223" y="392" font-family="DejaVu Serif, serif" font-size="52" font-weight="bold"
        fill="${INK}" text-anchor="middle">EIT</text>
  <text x="223" y="420" font-family="DejaVu Sans, sans-serif" font-size="16"
        fill="${INK}" text-anchor="middle">EXAMPLE INSTITUTE</text>
</svg>`;

/** Report body watermark — the crest without the wordmark. */
const watermarkSVG = `
<svg xmlns="http://www.w3.org/2000/svg" width="916" height="953" viewBox="0 0 916 953">
  <rect width="916" height="953" fill="#ffffff"/>
  <path d="M458 120 L742 212 v300 c0 186-128 296-284 348-156-52-284-162-284-348V212Z"
        fill="${INK}" stroke="${ACCENT}" stroke-width="18"/>
  <circle cx="458" cy="360" r="70" fill="${ACCENT}"/>
  <text x="458" y="760" font-family="DejaVu Serif, serif" font-size="120" font-weight="bold"
        fill="#ffffff" text-anchor="middle">EIT</text>
</svg>`;

async function emit(name, svg) {
  const file = path.join(OUT, name);
  if (await exists(file)) {
    console.log(`  skip  ${name} (already present)`);
    return;
  }
  const info = await sharp(Buffer.from(svg)).png({ compressionLevel: 9 }).toFile(file);
  console.log(`  write ${name.padEnd(16)} ${info.width}x${info.height}`);
}

await mkdir(OUT, { recursive: true });
await emit("banner.png", bannerSVG);
await emit("crest.png", crestSVG);
await emit("watermark.png", watermarkSVG);

await writeFile(
  path.join(OUT, "README.md"),
  `# Brand marks\n\n` +
  `These are generic placeholders, generated by \`node tools/make-placeholder-brand.mjs\`.\n\n` +
  `Replace them with your institution's own marks — any raster format, named\n` +
  `\`banner.*\`, \`crest.*\`, \`watermark.*\` — then run:\n\n` +
  "```\nnpm run brand\n```\n\n" +
  `which keys out white backgrounds, trims to the artwork, and derives the\n` +
  `reversed variant used on dark backgrounds. Output lands in \`brand/generated/\`.\n\n` +
  `Real institutional marks are trademarks; keep them out of a public repository.\n`,
  "utf8",
);
console.log(`\nwrote -> brand/logos/`);
