import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
import JSZip from 'jszip';
import { preview } from '../../../src/preview.js';
const root='docs/v2-8f-evidence/independent',records=[];
await mkdir(`${root}/browser-archives`,{recursive:true});
await mkdir(`${root}/browser-native`,{recursive:true});
const packet=JSON.parse(await readFile('docs/v2-8f-evidence/browser-archives.json','utf8'));
const sources=[...['chart','table'].map(kind=>({name:`fresh-shell-${kind}`,source:`out/v2-7a-validation/shell-${kind}.pptx`,fresh:true})),
  ...packet.filter(r=>!r.source.includes('v2-7a')).map(r=>({name:`retained-${path.basename(r.source,'.pptx')}`,source:r.originalArchive,fresh:false}))];
for(const row of sources){
 const bytes=await readFile(row.source),sha256=createHash('sha256').update(bytes).digest('hex'),zip=await JSZip.loadAsync(bytes);
 const slides=Object.keys(zip.files).filter(f=>/^ppt\/slides\/slide\d+\.xml$/.test(f));
 if(row.fresh){
  const saved=`${root}/browser-archives/${row.name}.pptx`;await writeFile(saved,bytes);row.originalArchive=saved;
  const slide=await zip.file('ppt/slides/slide1.xml').async('string');assert.equal(slides.length,1);
  if(row.name.endsWith('chart')){const f=Object.keys(zip.files).find(f=>/^ppt\/charts\/chart\d+\.xml$/.test(f));assert.ok((await zip.file(f).async('string')).includes('Shell edited'));assert.ok(slide.includes('<c:chart'));}
  else assert.ok(slide.includes('<a:tbl>')&&slide.includes('Shell edited'));
 }
 const result=await preview(path.resolve(row.source),{outDir:path.resolve(process.env.FORGE_VALIDATION_OUT,`native-${row.name}`)});
 assert.equal(result.pages.length,slides.length);const rasters=[];
 for(let i=0;i<result.pages.length;i++){const file=`${root}/browser-native/${row.name}-${i+1}.png`;await copyFile(result.pages[i],file);rasters.push({file,sha256:createHash('sha256').update(await readFile(file)).digest('hex')});}
 records.push({...row,sha256,bytes:bytes.length,slideCount:slides.length,rasters});
}
await writeFile(`${root}/browser-native.json`,JSON.stringify({implementationSha:'0cab854bce04b862060829812a9ab6ff0b765fd9',records,limitation:'Only two shell archives were freshly generated by the independently executed7A suite. Three packet B1/B2 originals were reused for independent fresh native rasterization, not rerun browser generation. Interactive Microsoft PowerPoint remains unexecuted.'},null,2)+'\n');
console.log('Two fresh shell archives and three retained packet browser archives independently rasterized.');
