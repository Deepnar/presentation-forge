import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { Pool } from 'pg';
import JSZip from 'jszip';
import { importApiFixture } from '../../../../test/v2-import-fixture.js';
import { preview } from '../../../../src/preview.js';

const output = new URL('./', import.meta.url).pathname;
const pool = new Pool({ connectionString: process.env.TEST_PG_URL, connectionTimeoutMillis: 3000 });
const database = `forge_c2_review_${process.pid}_${Date.now().toString(36)}`;
let fixture, created = false;
try {
  await pool.query(`CREATE DATABASE "${database}"`); created = true;
  const connection = new URL(process.env.TEST_PG_URL); connection.pathname = `/${database}`;
  fixture = await importApiFixture({ FORGE_PROJECTS_BACKEND: 'postgres', FORGE_PROJECTS_DATABASE_URL: connection.href });
  const source = await fixture.source();
  const originalBytes = await readFile(`${source.folder}/deck.yaml`);
  const response = await fixture.create(source.slug);
  assert.equal(response.status, 200);
  const original = (await response.json()).project;
  const request = (route, options = {}) => fixture.request(route, { token: fixture.token, ...options });
  const endpoint = `/api/v2/projects/${original.id}`;
  const cover = await request(`${endpoint}/cover?revision=0`).then(r => r.json());
  assert.deepEqual(cover.cover.scene, original.scenes[0]);
  assert.equal((await request(`${endpoint}/cover?revision=0`, { token: fixture.otherToken })).status, 404);
  const scenes = structuredClone(original.scenes);
  scenes[0].elements.find(element => element.kind === 'text').paragraphs[0].runs[0].text = 'Independent saved title';
  const saved = await request(endpoint, { method: 'PUT', body: JSON.stringify({ baseRevision: 0, scenes }) });
  assert.equal(saved.status, 200);
  assert.equal((await request(`${endpoint}/cover?revision=0`)).status, 409);
  assert.deepEqual((await request(`${endpoint}/cover?revision=1`).then(r => r.json())).cover.scene, scenes[0]);
  for (const route of ['/api/v2/projects', '/api/decks']) assert.equal((await request(route)).status, 200);
  assert.deepEqual(await readFile(`${source.folder}/deck.yaml`), originalBytes);
  const restored = await request(`${endpoint}/restore`, { method: 'POST', body: JSON.stringify({ revision: 0, baseRevision: 1 }) });
  assert.equal(restored.status, 200);
  const document = (await restored.json()).project;
  assert.equal(document.revision, 2); assert.deepEqual(document.scenes, original.scenes);
  assert.deepEqual((await request(`${endpoint}/cover?revision=2`).then(r => r.json())).cover.scene, document.scenes[0]);
  assert.equal((await request(`/api/decks/${source.slug}`, { method: 'DELETE' })).status, 200);
  assert.deepEqual((await request(endpoint).then(r => r.json())).project, document);
  const exported = await request(`${endpoint}/export.pptx`); assert.equal(exported.status, 200);
  const bytes = Buffer.from(await exported.arrayBuffer());
  await writeFile(`${output}/native.pptx`, bytes);
  const zip = await JSZip.loadAsync(bytes);
  const slides = Object.keys(zip.files).filter(file => /^ppt\/slides\/slide\d+\.xml$/.test(file));
  assert.equal(slides.length, 3);
  assert.ok((await zip.file('ppt/slides/slide1.xml').async('string')).includes('Imported results'));
  const chart = await zip.file(Object.keys(zip.files).find(file => /^ppt\/charts\/chart\d+\.xml$/.test(file))).async('string');
  assert.ok(chart.includes('1.25') && chart.includes('12.5'));
  const table = await zip.file('ppt/slides/slide3.xml').async('string');
  assert.ok(table.includes('<a:tbl>') && table.includes('Measurements') && table.includes('12.5'));
  await mkdir(`${output}/native`, { recursive: true });
  const rendered = await preview(`${output}/native.pptx`, { outDir: `${output}/native` });
  assert.equal(rendered.pages.length, 3);
  await writeFile(`${output}/native-inspection.json`, `${JSON.stringify({ implementationSha: 'bf1bd8f7dbce827be04ed530b2e7330b385e8baa', backend: 'PostgreSQL 15.18; unique disposable review database', checks: ['canonical cover equality', 'foreign cover refused', 'saved edit cover revision', 'stale cover refused', 'catalog reads preserve source bytes', 'restore-as-new revision', 'original deletion retains saved document', 'authenticated native text/chart/table export after source deletion'], sourceSha256: createHash('sha256').update(originalBytes).digest('hex'), exportSha256: createHash('sha256').update(bytes).digest('hex'), pages: rendered.pages.length, chartValues: [1.25, 12.5], inspectedVisually: false }, null, 2)}\n`);
  console.log('Fresh PostgreSQL cover/edit/history/delete-copy/native assertions pass; three pages rasterized. Visual inspection remains separate.');
} finally {
  await fixture?.stop();
  if (created) await pool.query(`DROP DATABASE "${database}"`);
  await pool.end();
}
